#!/usr/bin/env node
/**
 * Downloads the app's Google Fonts once into public/fonts/ and writes app/fonts.css:
 * the same @font-face rules Google serves (unicode-range subsets, so a browser only
 * fetches a script when it appears on screen) plus the --f-* variables templates use.
 *
 *   node scripts/fetch-fonts.mjs        (only when adding or changing a font)
 *
 * Why not next/font/google: it downloads at build time, and Google sometimes answers
 * build servers with font URLs it cannot parse ("Cannot read properties of null
 * (reading '1')"), which fails the Vercel build. Committed files make builds offline.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// [CSS variable, family, axes, fallback stack]
const FONTS = [
  ["--f-cinzel", "Cinzel", "wght@400;600", "serif"],
  ["--f-cormorant", "Cormorant Garamond", "ital,wght@0,400;0,500;0,600;1,400;1,500;1,600", "serif"],
  ["--f-vibes", "Great Vibes", "wght@400", "cursive"],
  ["--f-playfair", "Playfair Display", "ital,wght@0,400;0,600;1,400;1,600", "serif"],
  ["--f-marcellus", "Marcellus", "wght@400", "serif"],
  ["--f-inter", "Inter", "wght@300;400;500;600", "system-ui, sans-serif"],
  ["--f-devanagari", "Tiro Devanagari Hindi", "wght@400", "serif"],
  ["--f-bengali", "Tiro Bangla", "wght@400", "serif"],
  ["--f-caveat", "Caveat", "wght@400;600", "cursive"],
  ["--f-bodoni", "Bodoni Moda", "ital,wght@0,400;0,600;1,400;1,600", "serif"],
  ["--f-arabic", "Amiri", "wght@400;700", "serif"],
  ["--f-gurmukhi", "Noto Serif Gurmukhi", "wght@400;700", "serif"],
  ["--f-tamil", "Noto Serif Tamil", "wght@400;600", "serif"],
  ["--f-telugu", "Noto Serif Telugu", "wght@400;600", "serif"],
  ["--f-malayalam", "Noto Serif Malayalam", "wght@400;600", "serif"],
  ["--f-kannada", "Noto Serif Kannada", "wght@400;600", "serif"],
  ["--f-rozha", "Rozha One", "wght@400", "serif"],
  ["--f-kalam", "Kalam", "wght@400;700", "cursive"],
  ["--f-yatra", "Yatra One", "wght@400", "serif"],
  // App UI (site + editor), not used by templates: editorial serif, body sans, mono labels.
  ["--f-fraunces", "Fraunces", "ital,opsz,wght@0,9..144,400..800;1,9..144,400..800", "Georgia, serif"],
  ["--f-intertight", "Inter Tight", "wght@400;500;600;700", "system-ui, sans-serif"],
  ["--f-mono", "JetBrains Mono", "wght@400;500", "ui-monospace, monospace"],
];

// A modern Chrome UA makes Google answer with woff2 files split by unicode-range.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36";
const root = process.cwd();
const outDir = path.join(root, "public", "fonts");
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

let css =
  "/* Generated by scripts/fetch-fonts.mjs. Do not edit; re-run the script instead. */\n" +
  "/* Self-hosted Google Fonts (SIL Open Font License). */\n\n";
const vars = [];
let files = 0;
let bytes = 0;

for (const [cssVar, family, axes, fallback] of FONTS) {
  const url = "https://fonts.googleapis.com/css2?family=" + family.replace(/ /g, "+") + ":" + axes + "&display=swap";
  const res = await fetch(url, { headers: { "user-agent": UA } });
  if (!res.ok) throw new Error(family + ": HTTP " + res.status);
  let block = await res.text();
  const srcs = [...new Set([...block.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map((m) => m[1]))];
  if (!srcs.length) throw new Error(family + ": no font files in the CSS");
  for (const src of srcs) {
    const r = await fetch(src, { headers: { "user-agent": UA } });
    if (!r.ok) throw new Error(family + ": HTTP " + r.status + " for " + src);
    const buf = Buffer.from(await r.arrayBuffer());
    // Stable, versioned names (Google paths carry the font version) so they can be cached forever.
    const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    const name = slug + "-" + createHash("sha1").update(src).digest("hex").slice(0, 12) + ".woff2";
    fs.writeFileSync(path.join(outDir, name), buf);
    block = block.split("url(" + src + ")").join("url(/fonts/" + name + ")");
    files++;
    bytes += buf.length;
  }
  css += "/* ---- " + family + " ---- */\n" + block.trim() + "\n\n";
  vars.push("  " + cssVar + ": \"" + family + "\", " + fallback + ";");
  console.log(family.padEnd(24), srcs.length, "files");
}

css += ":root {\n" + vars.join("\n") + "\n}\n";
fs.writeFileSync(path.join(root, "app", "fonts.css"), css);
console.log("\n" + files + " files, " + Math.round(bytes / 1024) + " KB -> public/fonts/, app/fonts.css");
